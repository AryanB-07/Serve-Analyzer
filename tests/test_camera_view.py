def test_nothing_hidden_is_left_unexplained():
    """Each position's unreadable measurements are the ones its rig error exceeds the good range by."""
    table = json.loads(TABLE.read_text())["views"]
    for view in CAMERA_VIEWS:
        quality = measurement_quality(view, RANGES)
        for phase, by in quality.items():
            for metric, q in by.items():
                width = np.subtract(*RANGES[phase][metric]["good"][::-1])
                assert (q == UNREADABLE) == (table[view][f"{phase}.{metric}"] > width)
